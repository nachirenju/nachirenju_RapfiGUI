    // 3. 辞書から単一の巨大な正規表現（RegExp）を生成
    // これにより、O(N^2)のループがO(N)の一発置換になり、再翻訳も防げます
    let translationRegex = null;
    if (validKeys.length > 0) {
        const patternStr = validKeys.map(escapeRegExp).join('|');
        translationRegex = new RegExp(patternStr, 'g');
    }

    // 文字列を一括翻訳する関数
    function translateString(str) {
        if (!translationRegex || !str || typeof str !== 'string') return { text: str, changed: false };
        
        const originalStr = str;
        // 正規表現でマッチした箇所を辞書の値に置き換える（1パスのみ！）
        const translatedStr = str.replace(translationRegex, match => dictionary[match]);
        
        return { text: translatedStr, changed: originalStr !== translatedStr };
    }

